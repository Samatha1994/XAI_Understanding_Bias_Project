import os
import psycopg2
import re

from pipeline_config import get_config

# ============================================================
# Load config
# ============================================================
cfg = get_config()

DB_CONFIG         = cfg["db_config"]
FEATURES_TABLE    = cfg["features_table"]
RANGES_TABLE      = cfg["ranges_table"]
OWL_OUTPUT_DIR    = cfg["owl_output_dir"]
OWL_NAMESPACE     = cfg["owl_namespace"]
FILTER_ALGORITHMS = cfg["filter_algorithms"]  # empty list = ALL algorithms

print(f"▶ Active dataset     : {cfg['active_dataset']}")
print(f"▶ Database           : {cfg['db_name']}")
print(f"▶ Filter algorithms  : {FILTER_ALGORITHMS if FILTER_ALGORITHMS else 'ALL'}")
print(f"▶ OWL output dir     : {OWL_OUTPUT_DIR}")

# ============================================================
# Connect and load data
# ============================================================
conn = psycopg2.connect(**DB_CONFIG)
cur  = conn.cursor()

# Load bin ranges for all features
cur.execute(f"""
SELECT algorithm, feature_name, bin_start, bin_end, bin_label
FROM {RANGES_TABLE}
ORDER BY algorithm, feature_name, bin_start
""")

bin_lookup = {}
for alg, feat, b_start, b_end, label in cur.fetchall():
    key = (alg.strip().lower(), feat.strip().lower())
    bin_lookup.setdefault(key, []).append((b_start, b_end, label))

# Build algorithm filter clause
if FILTER_ALGORITHMS:
    algorithm_filter = "WHERE " + " OR ".join(
        [f"LOWER(TRIM(algorithm)) = '{alg.lower()}'" for alg in FILTER_ALGORITHMS]
    )
else:
    algorithm_filter = ""

# ── FIX: select image_path (full path) in addition to image_name ──
cur.execute(f"""
SELECT image_name, image_path, algorithm, feature_name, feature_value, class_name
FROM {FEATURES_TABLE}
{algorithm_filter}
ORDER BY image_path, algorithm, feature_name
""")

records = cur.fetchall()
cur.close()
conn.close()

# ── FIX: key feature_dict on image_path (unique) not image_name (basename, may collide) ──
feature_dict = {}
for image_name, image_path, algorithm, feature_name, feature_value, class_name in records:
    key = image_path  # full path is always unique
    if key not in feature_dict:
        feature_dict[key] = {"image_name": image_name, "class": class_name, "features": []}
    feature_dict[key]["features"].append((algorithm, feature_name, feature_value))


# ============================================================
# OWL generation helpers
# ============================================================

def clean_name_for_owl(name):
    cleaned = re.sub(r'[^a-zA-Z0-9\s]', '', name)
    return ''.join(word.capitalize() for word in cleaned.split())

def create_feature_class_name(algorithm, feature_name):
    return f"{clean_name_for_owl(algorithm)}_{clean_name_for_owl(feature_name)}"

def create_property_name(algorithm, feature_name):
    return f"has{clean_name_for_owl(algorithm)}_{clean_name_for_owl(feature_name)}"

def create_bin_class_name(feature_class, bin_start, bin_end):
    start_str = f"{bin_start:.5f}".replace(".", "_").replace("-", "neg")
    end_str   = f"{bin_end:.5f}".replace(".", "_").replace("-", "neg")
    return f"{feature_class}Bin_{start_str}_{end_str}"

def create_instance_name(feature_name, value):
    value_str = str(value).replace(".", "_").replace("-", "neg")
    return f"{clean_name_for_owl(feature_name)}_{value_str}"


def create_simple_owl(image_path, image_name, class_label, features, output_dir, split_name=""):
    filename     = os.path.basename(image_name)
    image_base   = os.path.splitext(filename)[0]
    class_folder = class_label.strip().replace(" ", "_").lower()

    # ── FIX: unique OWL individual identifier = class__basename
    #    This avoids collisions in the combined OWL when two images
    #    from different classes share the same filename.
    #    The .owl file on disk still saves as image_base.owl inside
    #    its class subfolder, so no filename collision there either.
    unique_id = f"{class_folder}__{image_base}"

    full_output_dir = os.path.join(output_dir, split_name, class_folder)
    os.makedirs(full_output_dir, exist_ok=True)

    owl_content = f"""@prefix : <{OWL_NAMESPACE}{unique_id}.owl#> .
@prefix owl: <http://www.w3.org/2002/07/owl#> .
@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix xml: <http://www.w3.org/XML/1998/namespace> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@base <{OWL_NAMESPACE}{unique_id}.owl> .

<{OWL_NAMESPACE}{unique_id}.owl> rdf:type owl:Ontology .

###  Generated by the OWL API (version 4.5.9.2019-02-01T07:24:44Z) https://github.com/owlcs/owlapi

#################
### Classes
#################

:Image rdf:type owl:Class .

"""

    feature_types = set()
    feature_bins  = {}

    for algorithm, feature_name, value in features:
        feature_class = create_feature_class_name(algorithm, feature_name)
        feature_types.add((feature_class, algorithm, feature_name))

        bin_key = (algorithm.strip().lower(), feature_name.strip().lower())
        for bin_start, bin_end, bin_label in bin_lookup.get(bin_key, []):
            if bin_start <= float(value) <= bin_end:
                bin_class = create_bin_class_name(feature_class, bin_start, bin_end)
                feature_bins[(feature_class, algorithm, feature_name)] = (bin_class, bin_start, bin_end, value)
                break

    current_algorithm = None
    for feature_class, algorithm, feature_name in sorted(feature_types):
        if current_algorithm != algorithm:
            current_algorithm = algorithm
            owl_content += f"# {algorithm.title()} Features\n"
        owl_content += f":{feature_class} rdf:type owl:Class .\n"
        if (feature_class, algorithm, feature_name) in feature_bins:
            bin_class, bin_start, bin_end, value = feature_bins[(feature_class, algorithm, feature_name)]
            owl_content += f":{bin_class} rdf:type owl:Class ; rdfs:subClassOf :{feature_class} .\n\n"

    owl_content += "#################\n### Object Properties\n#################\n\n"
    for feature_class, algorithm, feature_name in sorted(feature_types):
        property_name = create_property_name(algorithm, feature_name)
        owl_content += (
            f":{property_name} rdf:type owl:ObjectProperty ; "
            f"rdfs:domain :Image ; rdfs:range :{feature_class} .\n"
        )

    # ── FIX: use unique_id as the individual name (not image_base) ──
    owl_content += f"\n#################\n### Example Individual\n#################\n\n"
    owl_content += f":{unique_id} rdf:type :Image .\n\n"

    for feature_class, algorithm, feature_name in sorted(feature_types):
        if (feature_class, algorithm, feature_name) in feature_bins:
            bin_class, bin_start, bin_end, value = feature_bins[(feature_class, algorithm, feature_name)]
            property_name = create_property_name(algorithm, feature_name)
            instance_name = create_instance_name(feature_name, value)
            owl_content += f":{unique_id} :{property_name} :{instance_name} .\n"
            owl_content += f":{instance_name} rdf:type :{bin_class} .\n\n"

    # File on disk still uses image_base as filename (safe — lives in class subfolder)
    output_path = os.path.join(full_output_dir, f"{image_base}.owl")
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(owl_content)

    print(f"✅ Saved OWL for {image_path} → {output_path}")


# ============================================================
# Generate OWL files
# ============================================================
os.makedirs(OWL_OUTPUT_DIR, exist_ok=True)

# ── FIX: iterate over image_path keys; pass both path and name into the function ──
for image_path, data in feature_dict.items():
    create_simple_owl(
        image_path,
        data["image_name"],
        data["class"],
        data["features"],
        OWL_OUTPUT_DIR,
        split_name=""
    )

print(f"\n✅ All OWL files generated!")
print(f"📊 Processed {len(feature_dict)} images")
if FILTER_ALGORITHMS:
    print(f"🔍 Filtered for algorithms: {FILTER_ALGORITHMS}")
else:
    print("🌍 Included ALL algorithms and features")

if feature_dict:
    sample_data     = list(feature_dict.values())[0]
    sample_features = sample_data["features"]
    print(f"\n📋 Sample generated structure:")
    for alg, feat, val in sample_features[:3]:
        print(f"   Class    : {create_feature_class_name(alg, feat)}")
        print(f"   Property : {create_property_name(alg, feat)}")
        print(f"   ---")
